"""
Tests for data dictionary security hardening:
  1. _check_prompt_injection (data_dictionary.py)       - write-time blocking
  2. DataDictionaryService injection guards             - service layer validation
  3. SQLGenerationService._sanitize_dictionary_value    - runtime filtering
  4. SQLGenerationService._get_data_dictionary_context  - skips injected entries
  5. BusinessTermCreate model_validator                 - Pydantic scope_key enforcement
  6. API ownership validation (connection_hash checks)  - cross-connection prevention

All DB and Redis dependencies are mocked. No I/O occurs.
"""

import sys
