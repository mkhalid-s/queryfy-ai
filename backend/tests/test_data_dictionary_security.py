from unittest.mock import AsyncMock, MagicMock, patch

# ---------------------------------------------------------------------------
# Pre-mock heavy optional dependencies so tests can run without a full install.
# In CI (full venv) these are real; locally they may be missing.
# ---------------------------------------------------------------------------
def _mock_module(name: str) -> MagicMock:
    """Register a MagicMock as a sys.module if not already present."""
    if name not in sys.modules:
        mock = MagicMock()
        mock.__name__ = name
        mock.__spec__ = None
        sys.modules[name] = mock
    return sys.modules[name]

for _mod in [
    # SQLAlchemy and all sub-packages used in the dependency chain
    "sqlalchemy", "sqlalchemy.pool", "sqlalchemy.orm",
    "sqlalchemy.ext", "sqlalchemy.ext.asyncio",
    "sqlalchemy.dialects", "sqlalchemy.dialects.postgresql",
    "sqlalchemy.sql", "sqlalchemy.engine",
    # LiteLLM (used by llm_service → sql_generation)
    "litellm",
    # Vector DB
    "qdrant_client", "qdrant_client.models",
    # Telemetry
    "opentelemetry", "opentelemetry.trace",
    "opentelemetry.sdk", "opentelemetry.sdk.trace",
]:
    _mock_module(_mod)


