class TestBusinessTermCreateValidator:
    """Tests for the @model_validator that requires scope_key for tenant/session."""

    @pytest.fixture(autouse=True)
    def _import(self):
        from app.api.data_dictionary import BusinessTermCreate
        self.Model = BusinessTermCreate

    def _make(self, **kwargs):
        defaults = dict(
            term="Revenue",
            definition="Total revenue",
            sql_expression="SUM(revenue)",
        )
        defaults.update(kwargs)
        return self.Model(**defaults)

    # --- passing cases ---

    def test_global_scope_no_key_required(self):
        model = self._make(scope_type="global")
        assert model.scope_type == "global"

    def test_database_scope_no_key_required(self):
        model = self._make(scope_type="database")
        assert model.scope_type == "database"

    def test_session_scope_with_key(self):
        model = self._make(scope_type="session", scope_key="session-abc")
        assert model.scope_key == "session-abc"

    def test_tenant_scope_with_key(self):
        model = self._make(scope_type="tenant", scope_key="tenant-xyz")
        assert model.scope_key == "tenant-xyz"

    # --- failing cases ---

    def test_session_scope_without_key_raises(self):
        from pydantic import ValidationError
        with pytest.raises(ValidationError, match="scope_key"):
            self._make(scope_type="session", scope_key=None)

    def test_tenant_scope_without_key_raises(self):
        from pydantic import ValidationError
        with pytest.raises(ValidationError, match="scope_key"):
            self._make(scope_type="tenant", scope_key=None)

    def test_invalid_scope_type_raises(self):
        from pydantic import ValidationError
        with pytest.raises(ValidationError):
            self._make(scope_type="unknown_scope")


