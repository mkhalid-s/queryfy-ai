class TestAPIOwnershipValidation:
    """
    Tests that GET/PUT/DELETE term endpoints enforce connection_hash ownership.

    These are pure unit tests — data_dictionary service and session helpers
    are fully mocked.
    """

    @pytest.fixture(autouse=True)
    def _patches(self):
        """Patch all external dependencies for the API layer."""
        session_data = {
            "session_id": "sess-abc",
            "db_config": {
                "db_type": "postgresql",
                "connection_url": "postgresql://user:pass@localhost/db",
            },
        }

        with patch("app.api.data_dictionary.get_session", return_value=session_data), \
             patch("app.api.data_dictionary.vector_db") as mock_vdb, \
             patch("app.api.data_dictionary.data_dictionary") as mock_dd, \
             patch("app.api.data_dictionary.verify_csrf_token", return_value=None):

            mock_vdb._hash_connection.return_value = "hash-abc"
            self.mock_dd = mock_dd
            yield

    def _router(self):
        from app.api.data_dictionary import router
        from app.core.csrf_utils import verify_csrf_token
        from fastapi import FastAPI
        from fastapi.testclient import TestClient
        app = FastAPI()
        app.include_router(router, prefix="/api/v1/data-dictionary")
        # Override CSRF dependency — not under test here
        app.dependency_overrides[verify_csrf_token] = lambda: "test-token"
        return TestClient(app)

    # --- GET term: wrong connection → 404 ---

    def test_get_term_wrong_connection_returns_404(self):
        self.mock_dd.get_business_term = AsyncMock(return_value={
            "id": "t1",
            "term": "Revenue",
            "connection_hash": "hash-DIFFERENT",  # doesn't match session's hash-abc
            "definition": "...",
            "sql_expression": "...",
        })
        client = self._router()
        resp = client.get("/api/v1/data-dictionary/terms/t1?session_id=sess-abc")
        assert resp.status_code == 404

    def test_get_term_matching_connection_returns_200(self):
        self.mock_dd.get_business_term = AsyncMock(return_value={
            "id": "t1",
            "term": "Revenue",
            "connection_hash": "hash-abc",  # matches
            "definition": "Total revenue",
            "sql_expression": "SUM(revenue)",
            "scope_type": "database",
            "scope_key": None,
            "synonyms": [],
            "examples": [],
            "category": None,
            "is_active": True,
            "created_at": "2026-01-01T00:00:00",
            "updated_at": "2026-01-01T00:00:00",
        })
        client = self._router()
        resp = client.get("/api/v1/data-dictionary/terms/t1?session_id=sess-abc")
        assert resp.status_code == 200

    def test_get_term_not_found_returns_404(self):
        self.mock_dd.get_business_term = AsyncMock(return_value=None)
        client = self._router()
        resp = client.get("/api/v1/data-dictionary/terms/nonexistent?session_id=sess-abc")
        assert resp.status_code == 404

    # --- PUT term: wrong connection → 404 ---

    def test_put_term_wrong_connection_returns_404(self):
        self.mock_dd.get_business_term = AsyncMock(return_value={
            "id": "t1",
            "connection_hash": "hash-DIFFERENT",
        })
        client = self._router()
        resp = client.put(
            "/api/v1/data-dictionary/terms/t1?session_id=sess-abc",
            json={"definition": "Updated definition"},
        )
        assert resp.status_code == 404

    # --- DELETE term: wrong connection → 404 ---

    def test_delete_term_wrong_connection_returns_404(self):
        self.mock_dd.get_business_term = AsyncMock(return_value={
            "id": "t1",
            "connection_hash": "hash-DIFFERENT",
        })
        client = self._router()
        resp = client.delete("/api/v1/data-dictionary/terms/t1?session_id=sess-abc")
        assert resp.status_code == 404

    def test_delete_term_matching_connection_succeeds(self):
        self.mock_dd.get_business_term = AsyncMock(return_value={
            "id": "t1",
            "connection_hash": "hash-abc",
        })
        self.mock_dd.delete_business_term = AsyncMock(return_value=True)
        client = self._router()
        resp = client.delete("/api/v1/data-dictionary/terms/t1?session_id=sess-abc")
        assert resp.status_code == 200
